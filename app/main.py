@app.on_event("startup")
def add_sessions_column_if_missing():
    from sqlalchemy import text
    from .database import SessionLocal
    
    db = SessionLocal()
    try:
        bind_engine = db.get_bind()
        dialect_name = bind_engine.dialect.name
        
        logger.info(f"Startup check: database dialect is {dialect_name}")
        
        if dialect_name == "postgresql":
            db.execute(text("ALTER TABLE users ADD COLUMN IF NOT EXISTS sessions JSONB DEFAULT '[]'::jsonb"))
            db.commit()
            logger.info("Successfully checked/added 'sessions' JSONB column to PostgreSQL 'users' table.")
        else:
            try:
                db.execute(text("ALTER TABLE users ADD COLUMN sessions JSON"))
                db.commit()
                logger.info("Successfully added 'sessions' JSON column to SQLite 'users' table.")
            except Exception as e:
                logger.info(f"SQLite check finished (column may already exist): {e}")
    except Exception as e:
        logger.error(f"Error checking/adding sessions column: {e}")
    finally:
        db.close()

