@app.post("/save-session", response_model=schemas.SessionOut)
def save_session(payload: schemas.SessionCreate, db: Session = Depends(get_db)):
    """Save a session payload generated by the backend or frontend for a user inside the user table."""
    user = auth.get_user_by_email(db, payload.user_id)
    if not user:
        raise HTTPException(status_code=404, detail="User not found")
    
    # Initialize sessions list if it is None
    if user.sessions is None:
        user.sessions = []
    
    # We want to support updating an existing session in the list if the session_id matches,
    # or appending a new one if it doesn't.
    new_session_data = payload.session_data
    session_id = str(new_session_data.get("session_id") or new_session_data.get("id") or "")
    if not session_id:
        import time
        session_id = f"session_{int(time.time() * 1000)}"
        new_session_data["session_id"] = session_id
        new_session_data["id"] = session_id
    
    # Ensure created_at / updated_at in session data
    import datetime
    now_str = datetime.datetime.now().isoformat()
    if "created_at" not in new_session_data:
        new_session_data["created_at"] = now_str
    new_session_data["updated_at"] = now_str
    
    # Construct the full session object to store or update in the list
    session_item = {
        "id": session_id,
        "user_id": payload.user_id,
        "session_data": new_session_data,
        "created_at": new_session_data.get("created_at", now_str)
    }
    
    # Update or append in the sessions JSON list
    updated_sessions = []
    found = False
    for s in user.sessions:
        if isinstance(s, dict) and (str(s.get("id")) == session_id or str(s.get("session_data", {}).get("session_id")) == session_id):
            updated_sessions.append(session_item)
            found = True
        else:
            updated_sessions.append(s)
            
    if not found:
        updated_sessions.insert(0, session_item)
        
    # Assign the new list back to flag SQLAlchemy that the JSON column has changed
    from sqlalchemy.orm.attributes import flag_modified
    user.sessions = updated_sessions
    flag_modified(user, "sessions")
    
    db.commit()
    db.refresh(user)
    
    # Return formatted session out
    return {
        "id": session_item["id"],
        "user_id": session_item["user_id"],
        "session_data": session_item["session_data"],
        "created_at": datetime.datetime.fromisoformat(session_item["created_at"])
    }


@app.get("/sessions", response_model=List[schemas.SessionOut])
def get_sessions(user_id: Optional[str] = None, db: Session = Depends(get_db)):
    """List sessions. If user_id is provided, filter by that user_id."""
    import datetime
    all_sessions = []
    
    if user_id:
        user = auth.get_user_by_email(db, user_id)
        if not user or not user.sessions:
            return []
        
        # Format user sessions to match SessionOut
        for s in user.sessions:
            if isinstance(s, dict):
                created_at_val = s.get("created_at")
                if isinstance(created_at_val, str):
                    try:
                        created_dt = datetime.datetime.fromisoformat(created_at_val)
                    except Exception:
                        created_dt = datetime.datetime.now()
                else:
                    created_dt = datetime.datetime.now()
                
                all_sessions.append({
                    "id": str(s.get("id") or s.get("session_data", {}).get("session_id") or "0"),
                    "user_id": user.email,
                    "session_data": s.get("session_data", s),
                    "created_at": created_dt
                })
        return all_sessions
    else:
        # Get all sessions from all users for public repository
        users = db.query(models.User).all()
        for u in users:
            if u.sessions:
                for s in u.sessions:
                    if isinstance(s, dict):
                        created_at_val = s.get("created_at")
                        if isinstance(created_at_val, str):
                            try:
                                created_dt = datetime.datetime.fromisoformat(created_at_val)
                            except Exception:
                                created_dt = datetime.datetime.now()
                        else:
                            created_dt = datetime.datetime.now()
                            
                        all_sessions.append({
                            "id": str(s.get("id") or s.get("session_data", {}).get("session_id") or "0"),
                            "user_id": u.email,
                            "session_data": s.get("session_data", s),
                            "created_at": created_dt
                        })
        # Sort by created_at descending
        all_sessions.sort(key=lambda x: x["created_at"], reverse=True)
        return all_sessions


@app.post("/api/sessions/{session_id}/comment")
def add_comment(session_id: str, payload: dict, db: Session = Depends(get_db)):
    """Añade un comentario a una sesión pública guardada en la columna sessions de la tabla users."""
    author = payload.get("author", "Anónimo")
    text = payload.get("text", "")
    
    if not text:
        raise HTTPException(status_code=400, detail="El comentario no puede estar vacío")
        
    # Find the user owning this session_id
    users = db.query(models.User).all()
    user_found = None
    session_item = None
    
    for u in users:
        if u.sessions:
            for s in u.sessions:
                if isinstance(s, dict) and (str(s.get("id")) == session_id or str(s.get("session_data", {}).get("session_id")) == session_id):
                    user_found = u
                    session_item = s
                    break
            if user_found:
                break
                
    if not user_found or not session_item:
        raise HTTPException(status_code=404, detail="Sesión no encontrada")
        
    session_data = session_item.get("session_data", {})
    comments = session_data.get("comments", [])
    
    import datetime
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    
    new_comment = {
        "id": int(datetime.datetime.now().timestamp() * 1000),
        "author": author,
        "text": text,
        "time": now_str
    }
    
    comments.insert(0, new_comment)
    session_data["comments"] = comments
    session_item["session_data"] = session_data
    
    # Flag SQLAlchemy that the JSON column changed
    from sqlalchemy.orm.attributes import flag_modified
    flag_modified(user_found, "sessions")
    
    db.commit()
    return {"status": "ok", "comment": new_comment}


